-- ============================================================
-- Consistência de preços (o banco recusa, mesmo que o front-end falhe)
-- ============================================================
create or replace function public.brl(v numeric)
returns text language sql immutable as $$
  select 'R$ ' || replace(to_char(v, 'FM999999990.00'), '.', ',')
$$;

-- Ao criar/editar uma promoção: preço promocional tem de ser menor que o preço normal
create or replace function public.check_promotion_price()
returns trigger language plpgsql as $$
declare base numeric;
begin
  select price into base from public.products where id = new.product_id;
  if new.promo_price >= base then
    raise exception 'O preço promocional (%) precisa ser menor que o preço normal (%).',
      public.brl(new.promo_price), public.brl(base) using errcode = 'P0001';
  end if;
  return new;
end $$;
drop trigger if exists promotions_check_price on public.promotions;
create trigger promotions_check_price before insert or update of promo_price, product_id on public.promotions
  for each row execute function public.check_promotion_price();

-- Ao editar o preço de um produto: não pode ficar igual/menor que o da promoção dele
create or replace function public.check_product_price_vs_promotion()
returns trigger language plpgsql as $$
declare promo numeric;
begin
  select promo_price into promo from public.promotions
   where product_id = new.id and promo_price >= new.price limit 1;
  if promo is not null then
    raise exception 'Este produto tem promoção de %. O preço normal precisa continuar maior que ele. Edite ou exclua a promoção antes.',
      public.brl(promo) using errcode = 'P0001';
  end if;
  return new;
end $$;
drop trigger if exists products_check_price on public.products;
create trigger products_check_price before update of price on public.products
  for each row execute function public.check_product_price_vs_promotion();


-- ============================================================
-- RLS — leitura pública só do que está publicado; escrita só admin
-- ============================================================
alter table public.categories     enable row level security;
alter table public.products       enable row level security;
alter table public.product_images enable row level security;
alter table public.promotions     enable row level security;
alter table public.banners        enable row level security;
alter table public.site_content   enable row level security;

-- Leitura pública
drop policy if exists "public read categories" on public.categories;
create policy "public read categories" on public.categories
  for select to anon, authenticated using (is_published);

drop policy if exists "public read products" on public.products;
create policy "public read products" on public.products
  for select to anon, authenticated using (status = 'published');

drop policy if exists "public read product_images" on public.product_images;
create policy "public read product_images" on public.product_images
  for select to anon, authenticated using (
    exists (select 1 from public.products p where p.id = product_id and p.status = 'published')
  );

drop policy if exists "public read promotions" on public.promotions;
create policy "public read promotions" on public.promotions
  for select to anon, authenticated using (
    is_active
    and (starts_at is null or starts_at <= now())
    and (ends_at   is null or ends_at   >= now())
    and exists (select 1 from public.products p where p.id = product_id and p.status = 'published')
  );

drop policy if exists "public read banners" on public.banners;
create policy "public read banners" on public.banners
  for select to anon, authenticated using (
    is_active
    and (starts_at is null or starts_at <= now())
    and (ends_at   is null or ends_at   >= now())
  );

drop policy if exists "public read site_content" on public.site_content;
create policy "public read site_content" on public.site_content
  for select to anon, authenticated using (true);

-- Escrita e leitura total (rascunhos, ocultos, expirados): somente admin
do $$
declare t text;
begin
  foreach t in array array['categories','products','product_images','promotions','banners','site_content']
  loop
    execute format('drop policy if exists "admin all %1$s" on public.%1$I', t);
    execute format(
      'create policy "admin all %1$s" on public.%1$I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      t);
  end loop;
end $$;

-- ============================================================
-- Storage — bucket público para fotos (leitura por URL); só admin envia/apaga
-- ============================================================
-- Limite de 5 MB por arquivo e só imagens (o painel já reduz as fotos antes do envio)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update
  set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "admin upload product-images" on storage.objects;
create policy "admin upload product-images" on storage.objects
  for insert to authenticated with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "admin update product-images" on storage.objects;
create policy "admin update product-images" on storage.objects
  for update to authenticated using (bucket_id = 'product-images' and public.is_admin())
  with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "admin delete product-images" on storage.objects;
create policy "admin delete product-images" on storage.objects
  for delete to authenticated using (bucket_id = 'product-images' and public.is_admin());
