-- ---------- Funções auxiliares ----------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- ---------- Administradores ----------
-- Só guarda QUEM é admin (ligação com o login do Supabase Auth).
-- Nenhuma senha aqui: a senha fica no Supabase Auth.
create table if not exists public.admin_users (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
-- Cada usuário logado só enxerga a PRÓPRIA linha (serve para o painel
-- perguntar "eu sou admin?"). Ninguém escreve nesta tabela pela API:
-- o primeiro admin é inserido manualmente no SQL Editor (ver docs/GUIA-CONFIGURACAO.md).
drop policy if exists "read own admin row" on public.admin_users;
create policy "read own admin row" on public.admin_users
  for select to authenticated using (user_id = auth.uid());

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

-- ---------- Categorias ----------
create table if not exists public.categories (
  id           uuid primary key default gen_random_uuid(),
  slug         text not null unique,
  name         text not null,
  sort_order   integer not null default 0,
  is_published boolean not null default true,
  created_at   timestamptz not null default now()
);

-- ---------- Produtos ----------
-- status: draft = rascunho | published = aparece na loja | hidden = oculto
-- public_id: número curto usado pela vitrine (carrinho e links #produto-N).
--            Gerado automaticamente para produtos novos; os 5 produtos atuais
--            mantêm os números de js/products.js (ver seed.sql).
create table if not exists public.products (
  id          uuid primary key default gen_random_uuid(),
  public_id   integer generated by default as identity unique,
  name        text not null check (length(btrim(name)) > 0),
  description text not null default '',
  price       numeric(10,2) not null check (price > 0 and price < 100000),
  sizes       text[] not null default '{}' check (cardinality(sizes) > 0),
  in_stock    boolean not null default true,
  featured    boolean not null default false,
  category_id uuid references public.categories (id) on delete set null,
  status      text not null default 'draft' check (status in ('draft', 'published', 'hidden')),
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at before update on public.products
  for each row execute function public.set_updated_at();

-- ---------- Imagens dos produtos ----------
-- path: caminho no Storage (bucket product-images) OU caminho local legado
--       (ex.: assets/images/produto-01.webp) durante a migração.
-- A primeira (menor sort_order) é a foto principal.
create table if not exists public.product_images (
  id         uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete cascade,
  path       text not null,
  alt        text,
  sort_order integer not null default 0
);
create index if not exists product_images_product_idx on public.product_images (product_id, sort_order);

-- ---------- Promoções ----------
-- O preço ORIGINAL não é copiado para cá: vem sempre de products.price.
-- Regra: promo_price < products.price, garantida por triggers (abaixo).
create table if not exists public.promotions (
  id          uuid primary key default gen_random_uuid(),
  product_id  uuid not null references public.products (id) on delete cascade,
  promo_price numeric(10,2) not null check (promo_price > 0 and promo_price < 100000),
  starts_at   timestamptz,
  ends_at     timestamptz,
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  check (ends_at is null or starts_at is null or ends_at > starts_at)
);
-- No máximo uma promoção por produto: para mudar a oferta, edite-a; para pausar, desative.
create unique index if not exists promotions_product_uidx on public.promotions (product_id);

-- ---------- Banners ----------
create table if not exists public.banners (
  id         uuid primary key default gen_random_uuid(),
  title      text,
  image_path text not null,
  link_url   text,
  is_active  boolean not null default true,
  starts_at  timestamptz,
  ends_at    timestamptz,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- ---------- Conteúdo editável da página inicial ----------
